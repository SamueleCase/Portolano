//! The TypeScript bindings of the commands, `frontend/src/bindings.ts`
//! (SPEC-UI §2): generated, never edited by hand. `npm run bindings`
//! regenerates them; a test fails while the file is out of date.

use std::path::Path;

use specta_typescript::Typescript;

use crate::commands;

/// The first lines of the file.
const HEADER: &str = "// Generated by portolano-app (`npm run bindings`): do not edit.";

/// Writes the bindings to `path`.
///
/// # Errors
/// The errors of the TypeScript exporter: a type it cannot express, or a
/// failed write.
pub fn export_bindings(path: &Path) -> Result<(), specta_typescript::Error> {
    commands::builder::<tauri::Wry>().export(exporter(), path)
}

fn exporter() -> Typescript {
    Typescript::default().header(HEADER)
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::PathBuf;

    use portolano_core::{Issue, Severity};
    use portolano_import::{ImportReport, ItemStatus, ReportItem, TypeCounts};
    use portolano_ops::CleanupFailure;
    use portolano_ops::connect::LoginRequest;
    use portolano_ops::delete::{
        DeleteOutcome, DeletePreview, ExternalReference, PurgeOutcome, RestoreOutcome,
    };
    use portolano_ops::duplicate::DuplicateOutcome;
    use portolano_ops::import::ImportResult;
    use portolano_ops::inspect::{
        CredentialView, Entry, KeyView, NodeRef, NodeType, OriginView, SecretState,
    };
    use portolano_ops::nodes::{AddOutcome, EditOutcome};
    use portolano_ops::secrets::SecretSlot;
    use portolano_ops::trace::{CredentialTrace, SpecView, TraceEnd, TraceStep};
    use portolano_ops::usage::CredentialUsage;

    use super::*;

    /// Every result type of core, import and ops with the `specta` derive
    /// (SPEC-UI §3.5) exports to TypeScript, so that a command can return it
    /// as it is: a counter declared as `usize` without `specta(type = u32)`,
    /// for example, fails here rather than in the command that first uses it.
    #[test]
    fn result_types_of_the_libraries_export_to_typescript() {
        let builder = commands::builder::<tauri::Wry>()
            .typ::<Issue>()
            .typ::<Severity>()
            .typ::<ImportReport>()
            .typ::<TypeCounts>()
            .typ::<ReportItem>()
            .typ::<ItemStatus>()
            .typ::<ExternalReference>()
            .typ::<DeletePreview>()
            .typ::<NodeType>()
            .typ::<Entry>()
            .typ::<SecretState>()
            .typ::<OriginView>()
            .typ::<KeyView>()
            .typ::<CredentialView>()
            .typ::<LoginRequest>()
            .typ::<AddOutcome>()
            .typ::<CleanupFailure>()
            .typ::<EditOutcome>()
            .typ::<DeleteOutcome>()
            .typ::<RestoreOutcome>()
            .typ::<PurgeOutcome>()
            .typ::<DuplicateOutcome>()
            .typ::<ImportResult>()
            .typ::<NodeRef>()
            .typ::<SecretSlot>()
            .typ::<SpecView>()
            .typ::<TraceStep>()
            .typ::<TraceEnd>()
            .typ::<CredentialTrace>()
            .typ::<CredentialUsage>();
        let dir = tempfile::tempdir().unwrap();

        let exported = builder.export(exporter(), dir.path().join("bindings.ts"));

        assert!(exported.is_ok(), "{exported:?}");
    }

    /// The bindings in the repository, relative to this crate.
    fn committed_bindings() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../frontend/src/bindings.ts")
    }

    #[test]
    fn committed_bindings_are_up_to_date() {
        let dir = tempfile::tempdir().unwrap();
        let fresh = dir.path().join("bindings.ts");

        export_bindings(&fresh).unwrap();

        let committed = fs::read_to_string(committed_bindings()).unwrap_or_default();
        assert!(
            committed == fs::read_to_string(&fresh).unwrap(),
            "frontend/src/bindings.ts is out of date: run `npm run bindings` in frontend/"
        );
    }
}
